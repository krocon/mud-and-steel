//! Small-town map generator: `cli gen-town` (prompt 041).
//!
//! Builds a 600 m map around a small town: a main street (east-west) and a
//! cross street (north-south, from start to start) meet at a paved market
//! square with the town hall and the church; terraces of town houses line
//! both streets, warehouses stand behind the square, gardens hold hay and
//! firewood. Farms lie on the outskirts, woods west (split by the main
//! street: the road is a firebreak) and east, and each side has a supply
//! dump of ammunition and fuel in front of its start. Writes `map.toml`,
//! `height.png`, `terrain.png` and `objects.csv` (format: `docs/MAPS.md`).
//!
//! Like `gen_map` it runs outside the simulation and may use floats; it
//! only uses basic arithmetic, `sin`-free shapes and the simulation's
//! random generator, so the same seed gives the same files everywhere. No
//! real place names.

use crate::gen_map::{Random, write_png};
use sim::objects::CSV_HEADER;
use sim::{Rng, TerrainRules};
use std::fmt::Write as _;
use std::path::Path;

const CELL_M: f64 = 2.0;
const GRASS: u8 = 0;
const DIRT_TRACK: u8 = 1;
const ROAD: u8 = 2;

/// Half width of the paved streets (m).
const STREET_HALF: f64 = 4.0;
/// Half edge of the market square (m).
const SQUARE_HALF: f64 = 24.0;
/// Town houses: 12 m frontage (catalog `env_house_town`), 10 m deep, 3 m
/// from the street edge.
const HOUSE_LENGTH: f64 = 12.0;
const HOUSE_DEPTH: f64 = 10.0;
const SETBACK: f64 = 3.0;
/// Houses per terrace and the alley between terraces (m).
const TERRACE: usize = 4;
const ALLEY: f64 = 8.0;

/// Parameters of `cli gen-town`.
pub struct Options<'a> {
    pub name: &'a str,
    pub seed: u64,
    pub biome: &'a str,
    pub out: &'a Path,
}

/// The map is this wide and deep (m).
pub const SIZE_M: u32 = 600;

#[derive(Clone, Copy)]
struct Rect {
    x0: f64,
    y0: f64,
    x1: f64,
    y1: f64,
}

impl Rect {
    fn around(x: f64, y: f64, half_x: f64, half_y: f64) -> Self {
        Self {
            x0: x - half_x,
            y0: y - half_y,
            x1: x + half_x,
            y1: y + half_y,
        }
    }

    fn overlaps(&self, o: &Self, margin: f64) -> bool {
        self.x0 - margin < o.x1
            && o.x0 - margin < self.x1
            && self.y0 - margin < o.y1
            && o.y0 - margin < self.y1
    }
}

struct Town {
    random: Random,
    rows: Vec<String>,
    taken: Vec<Rect>,
    counts: Counts,
}

#[derive(Default)]
struct Counts {
    buildings: usize,
    trees: usize,
    dumps: usize,
    other: usize,
}

/// Ground type at `(x, y)`: streets, the square and farm tracks.
fn terrain_at(x: f64, y: f64) -> u8 {
    let square = x.abs() <= SQUARE_HALF && y.abs() <= SQUARE_HALF;
    let main_street = y.abs() <= STREET_HALF;
    let cross_street = x.abs() <= STREET_HALF;
    if square || main_street || cross_street {
        return ROAD;
    }
    // Farm tracks: north-south at x = +-160 between the fields.
    if (x.abs() - 160.0).abs() <= 2.5 && y.abs() <= 230.0 {
        return DIRT_TRACK;
    }
    GRASS
}

/// Gentle rolling ground, flat in the town (m).
fn height_at(x: f64, y: f64, bumps: &[(f64, f64, f64, f64)]) -> f64 {
    let mut h = 0.0;
    for &(bx, by, r, a) in bumps {
        let d2 = ((x - bx) * (x - bx) + (y - by) * (y - by)) / (r * r);
        if d2 < 1.0 {
            let t = 1.0 - d2;
            h += a * t * t;
        }
    }
    // Flatten towards the town center.
    let town = ((x.abs() - 90.0).max(0.0) + (y.abs() - 90.0).max(0.0)) / 120.0;
    h * town.min(1.0) + 0.002 * y
}

impl Town {
    fn new(seed: u64) -> Self {
        Self {
            random: Random(Rng::new(seed ^ 0x746f_776e)),
            rows: vec![
                "# Generated by `cli gen-town` (prompt 041, docs/MAPS.md). Rules: data/objects.toml."
                    .into(),
                CSV_HEADER.into(),
            ],
            taken: Vec::new(),
            counts: Counts::default(),
        }
    }

    /// Places an object with the given footprint half extents (x, y) unless
    /// it would overlap another one by `margin` or stand on a street.
    fn place(
        &mut self,
        (kind, variant): (&str, &str),
        (x, y): (f64, f64),
        heading: u16,
        (half_x, half_y): (f64, f64),
        margin: f64,
    ) -> bool {
        let rect = Rect::around(x, y, half_x, half_y);
        let limit = f64::from(SIZE_M) / 2.0 - 4.0;
        if rect.x0 < -limit || rect.x1 > limit || rect.y0 < -limit || rect.y1 > limit {
            return false;
        }
        if self.taken.iter().any(|t| t.overlaps(&rect, margin)) {
            return false;
        }
        for (cx, cy) in [
            (rect.x0, rect.y0),
            (rect.x1, rect.y0),
            (rect.x0, rect.y1),
            (rect.x1, rect.y1),
            (x, y),
        ] {
            if terrain_at(cx, cy) == ROAD {
                return false;
            }
        }
        self.taken.push(rect);
        self.rows.push(format!(
            "{kind},{variant},{},{},{heading}",
            (x * 1000.0).round() as i64,
            (y * 1000.0).round() as i64
        ));
        let counter = if kind.starts_with("env_tree") {
            &mut self.counts.trees
        } else if kind.starts_with("env_dump") {
            &mut self.counts.dumps
        } else if matches!(
            kind,
            "env_house_town"
                | "env_town_hall"
                | "env_warehouse"
                | "env_church"
                | "env_house_farm"
                | "env_barn"
                | "env_house_farm_brick"
        ) {
            &mut self.counts.buildings
        } else {
            &mut self.counts.other
        };
        *counter += 1;
        true
    }

    /// Terraces of town houses along a street. `along_x`: the street runs
    /// east-west at y = 0, else north-south at x = 0. `side` = +1 south or
    /// east of the street, -1 north or west.
    fn terraces(&mut self, along_x: bool, side: f64, from: f64, to: f64) {
        let offset = STREET_HALF + SETBACK + HOUSE_DEPTH / 2.0;
        let mut u = from;
        let mut in_terrace = 0;
        while u + HOUSE_LENGTH <= to {
            let c = u + HOUSE_LENGTH / 2.0;
            // Doors face the street: the model's +X (door side) must point
            // towards it (heading turns +X clockwise from east).
            let (x, y, heading, half) = if along_x {
                let heading = if side < 0.0 { 90 } else { 270 };
                (
                    c,
                    side * offset,
                    heading,
                    (HOUSE_LENGTH / 2.0, HOUSE_DEPTH / 2.0),
                )
            } else {
                let heading = if side < 0.0 { 0 } else { 180 };
                (
                    side * offset,
                    c,
                    heading,
                    (HOUSE_DEPTH / 2.0, HOUSE_LENGTH / 2.0),
                )
            };
            let variant = if self.random.unit() < 0.1 {
                "Damaged"
            } else {
                "Intact"
            };
            self.place(("env_house_town", variant), (x, y), heading, half, -0.01);
            // Gardens behind the house: hay and firewood.
            let back = offset + HOUSE_DEPTH / 2.0 + 6.0 + self.random.range(0.0, 6.0);
            let (gx, gy) = if along_x {
                (c, side * back)
            } else {
                (side * back, c)
            };
            if self.random.unit() < 0.5 {
                self.place(
                    ("env_woodpile", "Stack"),
                    (gx, gy),
                    if along_x { 90 } else { 0 },
                    (1.3, 1.3),
                    1.0,
                );
            } else if self.random.unit() < 0.6 {
                self.place(
                    ("env_hay_bale", "Rick"),
                    (gx, gy),
                    if along_x { 90 } else { 0 },
                    (2.0, 2.0),
                    1.0,
                );
            }
            in_terrace += 1;
            u += HOUSE_LENGTH;
            if in_terrace == TERRACE {
                in_terrace = 0;
                u += ALLEY;
            }
        }
    }

    /// A wood of `kind` trees on a jittered grid inside the rectangle,
    /// keeping `clear` meters off streets.
    fn wood(&mut self, kinds: &[(&'static str, &'static str)], r: Rect, spacing: f64) {
        let mut y = r.y0;
        while y <= r.y1 {
            let mut x = r.x0;
            while x <= r.x1 {
                let px = x + self.random.range(-1.2, 1.2);
                let py = y + self.random.range(-1.2, 1.2);
                let k = kinds[(self.random.unit() * kinds.len() as f64) as usize % kinds.len()];
                let clear = [(5.0, 0.0), (-5.0, 0.0), (0.0, 5.0), (0.0, -5.0)]
                    .iter()
                    .all(|(dx, dy)| terrain_at(px + dx, py + dy) != ROAD);
                if clear {
                    let heading = (self.random.unit() * 360.0) as u16 % 360;
                    self.place(k, (px, py), heading, (0.5, 0.5), 0.6);
                }
                x += spacing;
            }
            y += spacing;
        }
    }

    /// A farm: farmhouse and barn around a yard, hay ricks.
    fn farm(&mut self, x: f64, y: f64, heading: u16) {
        let (hx, hy, bx, by) = if heading == 0 {
            (4.5, 7.0, 5.0, 10.0)
        } else {
            (7.0, 4.5, 10.0, 5.0)
        };
        self.place(("env_house_farm", "Intact"), (x, y), heading, (hx, hy), 1.0);
        let (dx, dy) = if heading == 0 {
            (18.0, 0.0)
        } else {
            (0.0, 18.0)
        };
        self.place(
            ("env_barn", "Intact"),
            (x + dx, y + dy),
            heading,
            (bx, by),
            1.0,
        );
        for k in 0..3 {
            let ox = if heading == 0 {
                -6.0 + 7.0 * f64::from(k)
            } else {
                14.0
            };
            let oy = if heading == 0 {
                14.0
            } else {
                -6.0 + 7.0 * f64::from(k)
            };
            self.place(
                ("env_hay_bale", "Rick"),
                (x + ox, y + oy),
                heading,
                (2.0, 2.0),
                0.8,
            );
        }
        self.place(
            ("env_woodpile", "Stack"),
            (x - 4.0, y - 9.0),
            90,
            (1.3, 1.3),
            0.5,
        );
    }

    /// A supply dump: two ammunition stacks and two fuel dumps, 14 m apart
    /// (so one fire does not take them all at once, but a blast might).
    fn dump(&mut self, x: f64, y: f64) {
        self.place(
            ("env_dump_ammo", "Intact"),
            (x - 14.0, y),
            0,
            (2.0, 3.0),
            1.0,
        );
        self.place(("env_dump_ammo", "Intact"), (x, y), 0, (2.0, 3.0), 1.0);
        self.place(
            ("env_dump_fuel", "Intact"),
            (x + 14.0, y),
            0,
            (1.8, 2.4),
            1.0,
        );
        self.place(
            ("env_dump_fuel", "Intact"),
            (x + 14.0, y + 14.0),
            0,
            (1.8, 2.4),
            1.0,
        );
    }
}

/// Writes the town map into `options.out`.
pub fn generate(options: &Options) -> Result<String, String> {
    let rules = TerrainRules::builtin().map_err(|e| e.to_string())?;
    let size = f64::from(SIZE_M);
    let half = size / 2.0;
    let samples = (SIZE_M / 2 + 1) as usize;
    let mut town = Town::new(options.seed);
    let bumps: Vec<(f64, f64, f64, f64)> = (0..10)
        .map(|_| {
            let r = &mut town.random;
            (
                r.range(-half, half),
                r.range(-half, half),
                r.range(60.0, 140.0),
                r.range(-3.0, 6.0),
            )
        })
        .collect();

    let mut heights = Vec::with_capacity(samples * samples);
    let mut terrain = Vec::with_capacity(samples * samples);
    for j in 0..samples {
        for i in 0..samples {
            let x = i as f64 * CELL_M - half;
            let y = j as f64 * CELL_M - half;
            heights.push(height_at(x, y, &bumps));
            terrain.push(terrain_at(x, y));
        }
    }

    // Landmarks first, then terraces, farms, dumps, woods.
    town.place(
        ("env_town_hall", "Intact"),
        (-38.0, -36.0),
        90,
        (11.0, 6.5),
        1.0,
    );
    town.place(
        ("env_church", "Intact"),
        (45.0, -45.0),
        90,
        (10.0, 5.0),
        1.0,
    );
    town.place(
        ("env_warehouse", "Intact"),
        (-52.0, 46.0),
        90,
        (15.0, 8.0),
        1.0,
    );
    town.place(
        ("env_warehouse", "Damaged"),
        (52.0, 46.0),
        270,
        (15.0, 8.0),
        1.0,
    );
    let edge = SQUARE_HALF + 6.0;
    for side in [-1.0, 1.0] {
        town.terraces(true, side, -150.0, -edge);
        town.terraces(true, side, edge, 150.0);
        town.terraces(false, side, -150.0, -edge);
        town.terraces(false, side, edge, 150.0);
    }
    for (x, y, h) in [
        (-150.0, 200.0, 0),
        (150.0, 190.0, 90),
        (-150.0, -200.0, 90),
        (150.0, -190.0, 0),
        (-110.0, 110.0, 0),
        (110.0, -110.0, 90),
    ] {
        town.farm(x, y, h);
    }
    town.dump(40.0, 215.0);
    town.dump(-54.0, -215.0);
    // West wood, split by the main street (a firebreak).
    let conifers = [
        ("env_tree_conifer", "Spruce"),
        ("env_tree_conifer", "Pine"),
        ("env_tree_conifer", "SpruceYoung"),
    ];
    town.wood(
        &conifers,
        Rect {
            x0: -285.0,
            y0: -130.0,
            x1: -190.0,
            y1: 130.0,
        },
        6.0,
    );
    // East: mixed broadleaf wood and a birch grove.
    let broadleaf = [
        ("env_tree_deciduous", "Oak"),
        ("env_tree_deciduous", "Beech"),
        ("env_tree_deciduous", "OakYoung"),
    ];
    town.wood(
        &broadleaf,
        Rect {
            x0: 190.0,
            y0: -150.0,
            x1: 285.0,
            y1: 60.0,
        },
        6.5,
    );
    let birches = [
        ("env_tree_birch", "Birch"),
        ("env_tree_birch", "BirchYoung"),
    ];
    town.wood(
        &birches,
        Rect {
            x0: 200.0,
            y0: 100.0,
            x1: 260.0,
            y1: 150.0,
        },
        5.0,
    );
    // Orchards behind the terraces' far ends.
    town.wood(
        &broadleaf,
        Rect {
            x0: -140.0,
            y0: 40.0,
            x1: -100.0,
            y1: 80.0,
        },
        9.0,
    );
    town.wood(
        &broadleaf,
        Rect {
            x0: 100.0,
            y0: -80.0,
            x1: 140.0,
            y1: -40.0,
        },
        9.0,
    );

    let low = heights.iter().copied().fold(f64::MAX, f64::min);
    let high = heights.iter().copied().fold(f64::MIN, f64::max);
    let base_mm = ((low - 1.0).floor() * 1000.0) as i32;
    let encoded: Vec<u8> = heights
        .iter()
        .flat_map(|h| {
            let value = (h * 1000.0 - f64::from(base_mm)).round();
            (value.clamp(0.0, 65535.0) as u16).to_be_bytes()
        })
        .collect();
    std::fs::create_dir_all(options.out).map_err(|e| e.to_string())?;
    let side = samples as u32;
    write_png(&options.out.join("height.png"), side, &encoded, None)?;
    let palette: Vec<u8> = rules
        .types
        .iter()
        .flat_map(|t| {
            [
                (t.debug_color >> 16) as u8,
                (t.debug_color >> 8) as u8,
                t.debug_color as u8,
            ]
        })
        .collect();
    write_png(
        &options.out.join("terrain.png"),
        side,
        &terrain,
        Some(palette),
    )?;
    let mut csv = town.rows.join("\n");
    csv.push('\n');
    std::fs::write(options.out.join("objects.csv"), csv).map_err(|e| e.to_string())?;

    let mut toml = String::new();
    let _ = write!(
        toml,
        "# Generated by `cli gen-town` (prompt 041); edit the PNGs freely (docs/MAPS.md).\n\
         name = \"{}\"\n\
         generator = \"cli gen-town --name {} --seed {}\"\n\
         cell_size_mm = 2000\n\
         samples = [{side}, {side}]\n\
         height_base_mm = {base_mm}\n\
         height_step_mm = 1\n\
         biome = \"{}\"\n\
         water_flow_deg = 180\n\n\
         [[start]]\nplayer = 0\nposition_m = [0, 250]\n\n\
         [[start]]\nplayer = 1\nposition_m = [0, -250]\n\n\
         [[marker]]\nname = \"town_square\"\nposition_m = [0, 0]\n\n\
         [[marker]]\nname = \"west_wood\"\nposition_m = [-238, 0]\n\n\
         [[marker]]\nname = \"dump_south\"\nposition_m = [40, 215]\n\n\
         [[marker]]\nname = \"dump_north\"\nposition_m = [-54, -215]\n\n\
         [[marker]]\nname = \"supply_square\"\nposition_m = [0, 0]\n\n\
         [[marker]]\nname = \"supply_west\"\nposition_m = [-160, 0]\n\n\
         [[marker]]\nname = \"supply_east\"\nposition_m = [170, 80]\n",
        options.name, options.name, options.seed, options.biome,
    );
    std::fs::write(options.out.join("map.toml"), toml).map_err(|e| e.to_string())?;
    let c = &town.counts;
    Ok(format!(
        "wrote {}: {side} x {side} samples, heights {low:.2} .. {high:.2} m, {} objects ({} buildings, {} trees, {} dumps, {} other)",
        options.out.display(),
        c.buildings + c.trees + c.dumps + c.other,
        c.buildings,
        c.trees,
        c.dumps,
        c.other,
    ))
}

#[cfg(test)]
mod tests {
    use super::{Options, generate};
    use sim::Map;

    /// The generated town loads, has its buildings, dumps and woods, and
    /// the cross street joins both starts.
    #[test]
    fn town_map_loads_with_its_objects() {
        let dir = std::env::temp_dir().join(format!("mas-gen-town-{}", std::process::id()));
        let options = Options {
            name: "town_small",
            seed: 41,
            biome: "forest",
            out: &dir,
        };
        let report = generate(&options).unwrap();
        let read = |f: &str| std::fs::read(dir.join(f)).unwrap();
        let toml = String::from_utf8(read("map.toml")).unwrap();
        let mut map = Map::load(&toml, &read("height.png"), &read("terrain.png")).unwrap();
        map.add_objects(&String::from_utf8(read("objects.csv")).unwrap())
            .unwrap();
        let _ = std::fs::remove_dir_all(&dir);
        let count = |id: &str| {
            map.objects()
                .iter()
                .filter(|o| map.object_kinds()[usize::from(o.kind)].id == id)
                .count()
        };
        assert!(count("env_house_town") >= 40, "{report}");
        assert_eq!(count("env_town_hall"), 1);
        assert_eq!(count("env_warehouse"), 2);
        assert_eq!(count("env_dump_ammo"), 4);
        assert_eq!(count("env_dump_fuel"), 4);
        assert!(count("env_tree_conifer") > 300, "{report}");
    }
}
