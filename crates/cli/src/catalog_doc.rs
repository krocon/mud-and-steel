//! Renders `docs/UNIT_CATALOG.md` from the catalog. The document is never
//! edited by hand; a test checks that it matches the TOML files.

use sim::catalog::{Catalog, Entry, Faction, Group};
use std::fmt::Write;

/// Path of the generated document, relative to the workspace root.
pub const DOC_PATH: &str = "docs/UNIT_CATALOG.md";

const FACTIONS: [(Faction, &str); 5] = [
    (Faction::De, "Germany (`de`)"),
    (Faction::Su, "Soviet Union (`su`)"),
    (Faction::Us, "United States (`us`)"),
    (Faction::Uk, "Great Britain (`uk`)"),
    (Faction::Neutral, "Neutral (`neutral`)"),
];

const GROUPS: [Group; 6] = [
    Group::Infantry,
    Group::Vehicle,
    Group::Gun,
    Group::Fortification,
    Group::Aircraft,
    Group::Environment,
];

pub fn render(catalog: &Catalog) -> String {
    let mut out = String::new();
    out.push_str(
        "# Unit catalog\n\n\
         <!-- Generated by `just catalog-doc` from data/catalog/*.toml. Do not edit. -->\n\n\
         Real (unscaled) values from `data/catalog/`; field reference in\n\
         [`data/catalog/SCHEMA.md`](../data/catalog/SCHEMA.md), conversion to game values in\n\
         [SCALE.md](SCALE.md). Tier 1 = core units (prompt 006), tier 3 = taken over from the\n\
         vehicle references, not buildable (prompt 063). Values marked `?` are\n\
         uncertain; see the list at the end of each faction.\n\n",
    );
    for (faction, title) in FACTIONS {
        let entries: Vec<&Entry> = catalog
            .entries
            .iter()
            .filter(|e| e.faction == faction)
            .collect();
        if entries.is_empty() {
            continue;
        }
        let _ = writeln!(out, "## {title}\n");
        for group in GROUPS {
            let rows: Vec<&Entry> = entries
                .iter()
                .copied()
                .filter(|e| e.category.group() == group)
                .collect();
            if !rows.is_empty() {
                let _ = writeln!(out, "### {}\n", group.name());
                table(&mut out, group, &rows);
                out.push('\n');
            }
        }
        ranges_table(&mut out, &entries);
        uncertain_list(&mut out, &entries);
        sources_list(&mut out, &entries);
    }
    out
}

/// Every weapon with a range, once per name and pair of values (prompt
/// 067): the typical combat distance the simulation's direct fire uses, and
/// the maximum or sight value.
fn ranges_table(out: &mut String, entries: &[&Entry]) {
    let mut rows: Vec<(&str, Option<u32>, u32, Vec<&str>)> = Vec::new();
    for e in entries {
        for w in &e.weapon {
            let Some(effective) = w.range_effective_m else {
                continue;
            };
            match rows
                .iter_mut()
                .find(|r| r.0 == w.name && r.1 == w.range_typical_m && r.2 == effective)
            {
                Some(row) => row.3.push(&e.id),
                None => rows.push((&w.name, w.range_typical_m, effective, vec![&e.id])),
            }
        }
    }
    if rows.is_empty() {
        return;
    }
    out.push_str(
        "### Weapon ranges\n\n\
         Typical: the usual combat distance (`range_typical_m`), used by direct fire. \
         Effective: maximum or sight value, for indirect weapons (no typical value) the \
         maximum range the simulation uses.\n\n\
         | Weapon | Typical (m) | Effective (m) | Entries |\n|---|---|---|---|\n",
    );
    for (name, typical, effective, ids) in rows {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} |",
            escape(name),
            opt(typical),
            effective,
            ids.iter()
                .map(|id| format!("`{id}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    out.push('\n');
}

fn table(out: &mut String, group: Group, rows: &[&Entry]) {
    let header: &[&str] = match group {
        Group::Infantry => &["ID", "Name", "Tier", "Size", "Weapons"],
        Group::Vehicle => &[
            "ID",
            "Name",
            "Designation",
            "Years",
            "Tier",
            "L × W × H (m)",
            "Mass (t)",
            "Crew",
            "Road / off (km/h)",
            "Armor hull / turret front (mm)",
            "Main weapon",
        ],
        Group::Gun => &[
            "ID",
            "Name",
            "Years",
            "Tier",
            "L × W × H (m)",
            "Mass (kg)",
            "Crew",
            "Weapon",
            "Range (m)",
        ],
        Group::Aircraft => &[
            "ID",
            "Name",
            "Years",
            "Tier",
            "L × span × H (m)",
            "Mass (kg)",
            "Crew",
            "Max (km/h)",
            "Ceiling (m)",
        ],
        Group::Fortification | Group::Environment => {
            &["ID", "Name", "Tier", "L × W × H (m)", "Note"]
        }
    };
    let _ = writeln!(out, "| {} |", header.join(" | "));
    let _ = writeln!(out, "|{}", "---|".repeat(header.len()));
    for e in rows {
        let u = |field: &str, text: String| {
            if e.uncertain.iter().any(|f| f == field) {
                format!("{text}?")
            } else {
                text
            }
        };
        let name = format!("{} / {}", e.name_de, e.name_en);
        let years = match (e.year_from, e.year_to) {
            (Some(a), Some(b)) => format!("{a}–{b}"),
            _ => String::new(),
        };
        let main_weapon = e.weapon.first().map_or_else(String::new, weapon_text);
        let cells: Vec<String> = match group {
            Group::Infantry => vec![
                e.id.clone(),
                name,
                e.tier.to_string(),
                u("squad_size", opt(e.squad_size.map(u32::from))),
                u(
                    "weapon",
                    e.weapon
                        .iter()
                        .map(|w| format!("{}× {}", w.count, w.name))
                        .collect::<Vec<_>>()
                        .join(", "),
                ),
            ],
            Group::Vehicle => vec![
                e.id.clone(),
                name,
                e.designation.clone(),
                years,
                e.tier.to_string(),
                dims(e, "width_mm", e.width_mm),
                u("mass_kg", e.mass_kg.map_or_else(String::new, tonnes)),
                match e.passengers {
                    Some(p) => format!(
                        "{} + {}",
                        u("crew", opt(e.crew.map(u32::from))),
                        u("passengers", p.to_string())
                    ),
                    None => u("crew", opt(e.crew.map(u32::from))),
                },
                format!(
                    "{} / {}",
                    u("speed_road_kmh_x10", tenths(e.speed_road_kmh_x10)),
                    u("speed_offroad_kmh_x10", tenths(e.speed_offroad_kmh_x10))
                ),
                format!(
                    "{} / {}",
                    u(
                        "armor_hull_front_mm",
                        opt(e.armor_hull_front_mm.map(u32::from))
                    ),
                    u(
                        "armor_turret_front_mm",
                        opt(e.armor_turret_front_mm.map(u32::from))
                    )
                ),
                u("weapon", main_weapon),
            ],
            Group::Gun => vec![
                e.id.clone(),
                name,
                years,
                e.tier.to_string(),
                dims(e, "width_mm", e.width_mm),
                u("mass_kg", opt(e.mass_kg)),
                u("crew", opt(e.crew.map(u32::from))),
                u("weapon", main_weapon),
                u(
                    "weapon",
                    opt(e.weapon.first().and_then(|w| w.range_effective_m)),
                ),
            ],
            Group::Aircraft => vec![
                e.id.clone(),
                name,
                years,
                e.tier.to_string(),
                dims(e, "wingspan_mm", e.wingspan_mm),
                u("mass_kg", opt(e.mass_kg)),
                u("crew", opt(e.crew.map(u32::from))),
                u("speed_max_kmh_x10", tenths(e.speed_max_kmh_x10)),
                u("ceiling_m", opt(e.ceiling_m)),
            ],
            Group::Fortification | Group::Environment => vec![
                e.id.clone(),
                name,
                e.tier.to_string(),
                dims(e, "width_mm", e.width_mm),
                short(&e.note),
            ],
        };
        let cells: Vec<String> = cells.iter().map(|c| escape(c)).collect();
        let _ = writeln!(out, "| {} |", cells.join(" | "));
    }
}

fn uncertain_list(out: &mut String, entries: &[&Entry]) {
    let uncertain: Vec<&&Entry> = entries.iter().filter(|e| !e.uncertain.is_empty()).collect();
    if uncertain.is_empty() {
        return;
    }
    out.push_str("### Uncertain values\n\n");
    for e in uncertain {
        let _ = writeln!(out, "- `{}`: {}", e.id, e.uncertain.join(", "));
    }
    out.push('\n');
}

fn sources_list(out: &mut String, entries: &[&Entry]) {
    out.push_str("### Sources\n\n");
    for e in entries {
        let _ = writeln!(out, "- `{}`", e.id);
        for s in &e.source {
            let _ = writeln!(out, "  - {} ({})", s.reference, s.covers);
        }
    }
    out.push('\n');
}

fn weapon_text(w: &sim::catalog::Weapon) -> String {
    let count = if w.count > 1 {
        format!("{}× ", w.count)
    } else {
        String::new()
    };
    format!("{count}{}", w.name)
}

/// Length × second dimension × height in meters.
fn dims(e: &Entry, field: &str, second: Option<u32>) -> String {
    let part = |name: &str, v: Option<u32>| {
        let text = v.map_or_else(|| "–".into(), meters);
        if e.uncertain.iter().any(|f| f == name) {
            format!("{text}?")
        } else {
            text
        }
    };
    format!(
        "{} × {} × {}",
        part("length_mm", e.length_mm),
        part(field, second),
        part("height_mm", e.height_mm)
    )
}

fn opt(v: Option<u32>) -> String {
    v.map_or_else(String::new, |v| v.to_string())
}

/// Millimeters as meters with two decimals, rounded half up.
fn meters(mm: u32) -> String {
    let cm = (mm + 5) / 10;
    format!("{}.{:02}", cm / 100, cm % 100)
}

/// Kilograms as tonnes with one decimal, rounded half up.
fn tonnes(kg: u32) -> String {
    let t10 = (kg + 50) / 100;
    format!("{}.{}", t10 / 10, t10 % 10)
}

/// Tenths as a decimal number.
fn tenths(v: Option<u32>) -> String {
    v.map_or_else(String::new, |v| format!("{}.{}", v / 10, v % 10))
}

fn short(text: &str) -> String {
    let first = text.split(". ").next().unwrap_or("");
    if first.chars().count() > 80 {
        format!("{}…", first.chars().take(80).collect::<String>())
    } else {
        first.to_string()
    }
}

fn escape(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn number_formatting() {
        assert_eq!(meters(7020), "7.02");
        assert_eq!(meters(995), "1.00");
        assert_eq!(tonnes(25_000), "25.0");
        assert_eq!(tonnes(8_449), "8.4");
        assert_eq!(tenths(Some(380)), "38.0");
    }

    /// Acceptance criterion: the committed document matches the catalog.
    #[test]
    fn committed_doc_is_up_to_date() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/UNIT_CATALOG.md");
        let committed = std::fs::read_to_string(path).expect("docs/UNIT_CATALOG.md exists");
        let generated = render(&Catalog::builtin().expect("built-in catalog is valid"));
        assert!(
            committed.replace("\r\n", "\n") == generated,
            "docs/UNIT_CATALOG.md is out of date; run `just catalog-doc`"
        );
    }
}
