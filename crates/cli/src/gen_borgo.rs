//! Mediterranean village test map: `cli gen-borgo` (prompt 120).
//!
//! A 600 m map in the `mediterranean` biome with every object of the
//! prompt: a village of the Mediterranean family around a square (church
//! with campanile, town hall, rows of houses with shops and walled yards,
//! the editor's village brush), a farmstead (casale, barn) in the west, a
//! hill in the east with terrace walls along its contours, olive trees on
//! the terraces and a watch tower on top, a stone pine wood in the north,
//! cypresses along the lane, macchia in the south, a vineyard and a
//! stubble field. Two starts, west and east. Writes `map.toml`,
//! `height.png`, `terrain.png` and `objects.csv` (format: `docs/MAPS.md`).
//!
//! Ground like `gen_village` (floats, basic arithmetic only); objects
//! through `editor::EditMap` (integers), so the same seed gives the same
//! files everywhere. No real place names.

use crate::gen_map::{Random, write_png};
use crate::gen_village::{Placer, dist};
use editor::{EditMap, brush::Brush};
use sim::objects::CSV_HEADER;
use sim::{ObjectRules, Rng, TerrainRules};
use std::fmt::Write as _;
use std::path::Path;

const CELL_M: f64 = 2.0;
const GROUND: u8 = 0;
const DIRT_TRACK: u8 = 1;
const ROAD: u8 = 2;
const FIELD_GRAIN: u8 = 9;
const FIELD_GREEN: u8 = 10;

/// The map is this wide and deep (m).
pub const SIZE_M: u32 = 600;
/// Village square half edge and village radius (m).
const SQUARE_HALF: f64 = 18.0;
const VILLAGE_R: f64 = 110.0;
/// The terraced hill: center, radius of its foot (m) and height (m).
const HILL: (f64, f64) = (185.0, -40.0);
const HILL_R: f64 = 95.0;
const HILL_H: f64 = 22.0;
/// Farmstead (casale) center (m).
const FARM: (f64, f64) = (-180.0, 110.0);
const STARTS: [(u8, u8, i32, i32); 2] = [(0, 0, -250, -200), (1, 1, 250, 220)];

/// Parameters of `cli gen-borgo`.
pub struct Options<'a> {
    pub name: &'a str,
    pub seed: u64,
    pub out: &'a Path,
}

/// Height (m): the hill east of the village, gentle elsewhere.
fn height_at(x: f64, y: f64) -> f64 {
    let d = dist(x, y, HILL);
    let hill = if d < HILL_R {
        let t = 1.0 - d / HILL_R;
        HILL_H * t * t * (3.0 - 2.0 * t)
    } else {
        0.0
    };
    hill + 0.004 * y + 0.002 * x
}

/// Ground type at `(x, y)`.
fn terrain_at(x: f64, y: f64) -> u8 {
    if x.abs() <= SQUARE_HALF && y.abs() <= SQUARE_HALF {
        return ROAD;
    }
    // The lane west-east through the village and the track north-south.
    if y.abs() <= 3.0 && x < HILL.0 - HILL_R * 0.7 {
        return ROAD;
    }
    if x.abs() <= 2.5 {
        return DIRT_TRACK;
    }
    // Vineyard south-west and a stubble field north-west.
    if (-260.0..=-150.0).contains(&x) && (-230.0..=-140.0).contains(&y) {
        return FIELD_GREEN;
    }
    if (-120.0..=-30.0).contains(&x) && (150.0..=250.0).contains(&y) {
        return FIELD_GRAIN;
    }
    GROUND
}

/// Writes the Mediterranean village test map into `options.out`.
pub fn generate(options: &Options) -> Result<String, String> {
    let rules = TerrainRules::builtin().map_err(|e| e.to_string())?;
    let object_rules = ObjectRules::builtin().map_err(|e| e.0)?;
    let half = f64::from(SIZE_M) / 2.0;
    let samples = (SIZE_M / 2 + 1) as usize;
    let mut heights = Vec::with_capacity(samples * samples);
    let mut terrain = Vec::with_capacity(samples * samples);
    for j in 0..samples {
        for i in 0..samples {
            let x = i as f64 * CELL_M - half;
            let y = j as f64 * CELL_M - half;
            heights.push(height_at(x, y));
            terrain.push(terrain_at(x, y));
        }
    }
    let low = heights.iter().copied().fold(f64::MAX, f64::min);
    let high = heights.iter().copied().fold(f64::MIN, f64::max);
    let base_mm = ((low - 1.0).floor() * 1000.0) as i32;
    let encoded: Vec<u8> = heights
        .iter()
        .flat_map(|h| {
            let value = (h * 1000.0 - f64::from(base_mm)).round();
            (value.clamp(0.0, 65535.0) as u16).to_be_bytes()
        })
        .collect();
    std::fs::create_dir_all(options.out).map_err(|e| e.to_string())?;
    let side = samples as u32;
    write_png(&options.out.join("height.png"), side, &encoded, None)?;
    let palette: Vec<u8> = rules
        .types
        .iter()
        .flat_map(|t| {
            [
                (t.debug_color >> 16) as u8,
                (t.debug_color >> 8) as u8,
                t.debug_color as u8,
            ]
        })
        .collect();
    write_png(
        &options.out.join("terrain.png"),
        side,
        &terrain,
        Some(palette),
    )?;
    std::fs::write(options.out.join("objects.csv"), format!("{CSV_HEADER}\n"))
        .map_err(|e| e.to_string())?;
    let mut toml = String::new();
    let _ = write!(
        toml,
        "# Generated by `cli gen-borgo` (prompt 120); edit the PNGs freely (docs/MAPS.md).\n\
         name = \"{}\"\n\
         generator = \"cli gen-borgo --name {} --seed {}\"\n\
         cell_size_mm = 2000\n\
         samples = [{side}, {side}]\n\
         height_base_mm = {base_mm}\n\
         height_step_mm = 1\n\
         biome = \"mediterranean\"\n\
         water_flow_deg = 180\n",
        options.name, options.name, options.seed,
    );
    for &(player, team, x, y) in &STARTS {
        let _ = write!(
            toml,
            "\n[[start]]\nplayer = {player}\nteam = {team}\nposition_m = [{x}, {y}]\n"
        );
    }
    let m = |v: f64| v.round() as i32;
    for (name, (x, y)) in [
        ("village", (0.0, 0.0)),
        ("church", (-34.0, -40.0)),
        ("terraces", (HILL.0 - 55.0, HILL.1 + 20.0)),
        ("farm", FARM),
        ("supply_square", (0.0, 0.0)),
        ("supply_hill", HILL),
        ("supply_farm", FARM),
    ] {
        let _ = write!(
            toml,
            "\n[[marker]]\nname = \"{name}\"\nposition_m = [{}, {}]\n",
            m(x),
            m(y)
        );
    }
    std::fs::write(options.out.join("map.toml"), toml).map_err(|e| e.to_string())?;

    let mut map = EditMap::load_dir(options.out)?;
    map.set_seed(options.seed);
    let mm = |v: f64| (v * 1000.0).round() as i32;
    // The square: church north-west, town hall south-west, rows east.
    map.place_compound("med_church_yard", mm(-34.0), mm(-40.0), 90)?;
    map.place_compound("med_town_hall", mm(-32.0), mm(30.0), 0)?;
    map.place_compound("med_row", mm(29.0), mm(-25.0), 270)?;
    map.place_compound("med_row_short", mm(29.0), mm(24.0), 90)?;
    map.place_compound("med_casale", mm(FARM.0), mm(FARM.1), 0)?;
    map.place_compound("med_tower", mm(HILL.0), mm(HILL.1), 0)?;
    let compounds = map.village_of(Brush::new(0, 0, mm(VILLAGE_R) as u32), "mediterranean")?;
    let mut placer = Placer {
        map,
        rules: &object_rules,
        random: Random(Rng::new(options.seed ^ 0x6d65_6469)),
    };
    // Terraces: wall segments along the hill's contour rings (soil uphill,
    // towards the center), olives on the steps between them.
    let mut terraces = 0;
    for ring in [30.0, 44.0, 58.0, 72.0] {
        let n = (2.0 * std::f64::consts::PI * ring / 4.0).floor() as i32;
        for k in 0..n {
            let a = f64::from(k) * 2.0 * std::f64::consts::PI / f64::from(n);
            // Only the west half of the hill faces the village.
            if a.cos() > 0.25 {
                continue;
            }
            let (x, y) = (HILL.0 + ring * a.cos(), HILL.1 + ring * a.sin());
            // The model's +X (soil side) points to the hill top, its +Y
            // along the wall: the direction (cos a, sin a) away from the top
            // has the compass bearing 90° + a (x east, y south), the top
            // lies at a + 270°, and +X is the heading + 90°.
            let heading = (f64::from(k) * 360.0 / f64::from(n) + 180.0).round() as u16 % 360;
            if placer.put("env_terrace_wall", "Segment", (x, y), heading) {
                terraces += 1;
            }
        }
    }
    let olives = [
        ("env_tree_olive", "Olive"),
        ("env_tree_olive", "Olive"),
        ("env_tree_olive", "OliveOld"),
        ("env_tree_olive", "OliveYoung"),
    ];
    let mut trees = placer.grove(&olives, HILL, (22.0, 88.0), 8.0, 2500, |_| 0.85);
    let pines = [
        ("env_tree_stone_pine", "StonePine"),
        ("env_tree_stone_pine", "StonePine"),
        ("env_tree_stone_pine", "StonePineYoung"),
        ("env_tree_stone_pine", "StonePineLeaning"),
    ];
    trees += placer.grove(&pines, (40.0, 215.0), (0.0, 70.0), 11.0, 3000, |_| 0.8);
    // Cypresses along the lane west of the village and around the farm.
    for k in 0..12 {
        let x = -VILLAGE_R - 10.0 - f64::from(k) * 9.0;
        for y in [-7.0, 7.0] {
            if placer.put("env_tree_cypress", "Cypress", (x, y), 0) {
                trees += 1;
            }
        }
    }
    let macchia = [
        ("env_bush_macchia", "Holm"),
        ("env_bush_macchia", "Strawberry"),
        ("env_bush_macchia", "Broom"),
    ];
    let mut bushes = placer.grove(&macchia, (60.0, -230.0), (0.0, 80.0), 5.0, 1500, |_| 0.6);
    bushes += placer.grove(
        &macchia,
        HILL,
        (HILL_R - 10.0, HILL_R + 30.0),
        7.0,
        1500,
        |_| 0.4,
    );
    // Field-stone walls along the lane east of the village (with a gate).
    let mut walls = 0;
    for k in 0..10 {
        let x = VILLAGE_R + 2.0 + f64::from(k) * 3.0;
        let variant = match k {
            4 => "Gate",
            7 => "Broken",
            _ => "Segment",
        };
        if placer.put("env_wall_field", variant, (x, -6.0), 90) {
            walls += 1;
        }
    }
    let mut map = placer.map;
    for &(_, _, sx, sy) in &STARTS {
        map.erase(Brush::new(sx * 1000, sy * 1000, 40_000), None);
    }
    map.save_dir(options.out)?;
    let objects = map.objects();
    let count = |prefix: &str| {
        objects
            .iter()
            .filter(|o| o.kind.starts_with(prefix))
            .count()
    };
    Ok(format!(
        "wrote {}: {side} x {side} samples, heights {low:.2} .. {high:.2} m, {} objects \
         ({compounds} village compounds, {} houses, {terraces} terrace walls, {walls} lane walls, \
         {trees} trees, {bushes} macchia)",
        options.out.display(),
        objects.len(),
        count("env_house_med"),
    ))
}

#[cfg(test)]
mod tests {
    use super::{Options, generate};
    use sim::{Biome, Map};

    /// The generated map loads, is Mediterranean and holds the new objects.
    #[test]
    fn borgo_map_loads_with_its_objects() {
        let dir = std::env::temp_dir().join(format!("mas-gen-borgo-{}", std::process::id()));
        let report = generate(&Options {
            name: "borgo_test",
            seed: 120,
            out: &dir,
        })
        .unwrap();
        let read = |f: &str| std::fs::read(dir.join(f)).unwrap();
        let toml = String::from_utf8(read("map.toml")).unwrap();
        let mut map = Map::load(&toml, &read("height.png"), &read("terrain.png")).unwrap();
        assert_eq!(map.biome(), Biome::Mediterranean);
        let csv = std::fs::read_to_string(dir.join("objects.csv")).unwrap();
        map.add_objects(&csv).unwrap();
        for kind in [
            "env_church_med",
            "env_town_hall_med",
            "env_house_med_row",
            "env_house_med_casale",
            "env_barn_med",
            "env_tower_coast",
            "env_terrace_wall",
            "env_wall_field",
            "env_tree_olive",
            "env_tree_stone_pine",
            "env_tree_cypress",
            "env_bush_macchia",
        ] {
            assert!(csv.contains(kind), "{kind} missing: {report}");
        }
        let _ = std::fs::remove_dir_all(&dir);
    }
}
