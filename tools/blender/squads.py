"""Infantry squads (prompt 006): a squad is a catalog unit made of soldiers of
prompt 005 standing in a formation.

Source: `assets-src/blueprints/<faction>/squads/<id>.toml` (one per catalog
infantry entry). Output: `godot/assets/models/<faction>/<id>.tscn`, a Godot
scene that instances `godot/assets/models/<faction>/infantry/<role>.glb` once
per member. The catalog entry's `model` points to that scene. Generated; never
edit the .tscn by hand.

Runs with Blender's Python (needs tomllib, no bpy), like the other tools:

    blender -b --factory-startup --python-exit-code 1 --python tools/blender/squads.py -- build [<faction>/<id> ...]
    blender -b --factory-startup --python-exit-code 1 --python tools/blender/squads.py -- validate

Blueprint format:

    unit = "de_inf_mg42_team"          # catalog id, must match the file name
    [[member]]
    role = "mg_gunner"                 # soldier role (tools/blender/soldier/loadouts.py)
    position = [0.0, 1.0]              # [x, y] in m, model space (x right, y forward)
    clip = "aim_prone"                 # clip shown in the gallery (default idle)
    carries = ["MG 42", "P 38"]        # catalog weapon names this member stands for

Checks (`validate`): catalog entry exists and is infantry; member count equals
`squad_size`; every role exists for the faction and its soldier .glb is built;
the members' `carries` add up exactly to the catalog `weapon` counts; the
catalog `model` field names the scene; the scene is up to date.
"""

import json
import sys
import tomllib
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kit import catalog  # noqa: E402
from soldier import loadouts  # noqa: E402

REPO_ROOT = catalog.REPO_ROOT
MEMBER_KEYS = {"role", "position", "clip", "carries"}


def blueprint_path(faction, uid):
    return catalog.BLUEPRINT_DIR / faction / "squads" / f"{uid}.toml"


def scene_path(faction, uid):
    return catalog.MODEL_DIR / faction / f"{uid}.tscn"


def model_field(faction, uid):
    return f"assets/models/{faction}/{uid}.tscn"


def all_squads():
    out = []
    for faction in catalog.FACTIONS:
        d = catalog.BLUEPRINT_DIR / faction / "squads"
        if d.is_dir():
            out += [(faction, p.stem) for p in sorted(d.glob("*.toml"))]
    return out


def load(faction, uid):
    path = blueprint_path(faction, uid)
    with open(path, "rb") as f:
        bp = tomllib.load(f)
    if bp.get("unit") != uid:
        raise ValueError(f"{path}: 'unit' must be {uid!r}")
    extra = sorted(set(bp) - {"unit", "member"})
    if extra:
        raise KeyError(f"{path}: unknown keys {extra}")
    for i, m in enumerate(bp.get("member", []), start=1):
        bad = sorted(set(m) - MEMBER_KEYS)
        if bad or "role" not in m or "position" not in m:
            raise KeyError(f"{path}: member #{i}: needs role and position, unknown keys {bad}")
    return bp


def _gd(value):
    """Godot text-resource literal for str/int/float/bool/list/dict."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(_gd(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{\n" + ",\n".join(f"{_gd(k)}: {_gd(v)}" for k, v in value.items()) + "\n}"
    raise TypeError(f"no Godot literal for {value!r}")


def _num(v):
    v = round(float(v), 4)
    return "0" if v == 0 else (str(int(v)) if v == int(v) else repr(v))


def render_scene(faction, uid):
    """Text of the generated .tscn."""
    bp = load(faction, uid)
    u = catalog.unit(faction, uid)
    members = bp["member"]
    roles = sorted({m["role"] for m in members}, key=[m["role"] for m in members].index)
    res_id = {r: f"{i}_{r}" for i, r in enumerate(roles, start=1)}
    extras = catalog.summary(u)
    extras["cat_squad_size"] = u.get("squad_size", 0)
    extras["squad"] = True
    extras["squad_roles"] = [m["role"] for m in members]
    lines = [
        f"[gd_scene load_steps={len(roles) + 1} format=3]",
        "",
        f"; Generated by tools/blender/squads.py from assets-src/blueprints/{faction}/squads/{uid}.toml.",
        "; Do not edit; run `just squad " + f"{faction} {uid}`.",
        "",
    ]
    for r in roles:
        lines.append(f'[ext_resource type="PackedScene" path="res://assets/models/{faction}/infantry/{r}.glb" '
                     f'id="{res_id[r]}"]')
    lines += ["", f'[node name="{uid}" type="Node3D"]', f"metadata/extras = {_gd(extras)}", ""]
    for i, m in enumerate(members, start=1):
        x, y = m["position"]
        # Blender model space (x right, y forward, z up) -> Godot (x right, -z forward, y up)
        lines += [
            f'[node name="M{i:02d}_{m["role"]}" parent="." instance=ExtResource("{res_id[m["role"]]}")]',
            f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, {_num(x)}, 0, {_num(-y)})",
            f"metadata/role = {_gd(m['role'])}",
            f"metadata/clip = {_gd(m.get('clip', 'idle'))}",
            f"metadata/seed = {i}",
            "",
        ]
    return "\n".join(lines)


def build(faction, uid):
    text = render_scene(faction, uid)
    out = scene_path(faction, uid)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"squads: {faction}/{uid} -> {out.relative_to(REPO_ROOT)}")


def validate(faction, uid):
    errors = []
    try:
        bp = load(faction, uid)
        u = catalog.unit(faction, uid)
    except Exception as exc:
        return [str(exc)]
    if not u.get("category", "").startswith("inf_"):
        errors.append(f"catalog category {u.get('category')!r} is not infantry")
    members = bp.get("member", [])
    if len(members) != u.get("squad_size"):
        errors.append(f"{len(members)} members, catalog squad_size {u.get('squad_size')}")
    clips = _known_clips()
    for i, m in enumerate(members, start=1):
        role = m["role"]
        if faction not in loadouts.ROLES.get(role, {}):
            errors.append(f"member #{i}: role {role!r} does not exist for {faction}")
            continue
        glb = catalog.MODEL_DIR / faction / "infantry" / f"{role}.glb"
        if not glb.exists():
            errors.append(f"member #{i}: {glb.relative_to(REPO_ROOT)} missing (run `just soldier {faction} {role}`)")
        clip = m.get("clip", "idle")
        if clips and clip not in clips:
            errors.append(f"member #{i}: unknown clip {clip!r}")
    for i, a in enumerate(members):
        for b in members[i + 1:]:
            if (a["position"][0] - b["position"][0]) ** 2 + (a["position"][1] - b["position"][1]) ** 2 < 0.8 ** 2:
                errors.append(f"members {a['role']} and {b['role']} stand closer than 0.8 m")
    carried = Counter(w for m in members for w in m.get("carries", []))
    listed = Counter({w["name"]: w.get("count", 1) for w in u.get("weapon", [])})
    for name in sorted(set(carried) | set(listed)):
        if carried[name] != listed[name]:
            errors.append(f"weapon {name!r}: members carry {carried[name]}, catalog lists {listed[name]}")
    if u.get("model", "") != model_field(faction, uid):
        errors.append(f"catalog entry model = {u.get('model', '')!r}, expected {model_field(faction, uid)!r}")
    out = scene_path(faction, uid)
    if not out.exists():
        errors.append(f"{out.relative_to(REPO_ROOT)} missing (run `just squad {faction} {uid}`)")
    elif out.read_text() != render_scene(faction, uid):
        errors.append(f"{out.relative_to(REPO_ROOT)} is stale (run `just squad {faction} {uid}`)")
    return errors


def _known_clips():
    path = catalog.MODEL_DIR / "infantry" / "animations.json"
    if not path.exists():
        return None
    return set(json.loads(path.read_text()).get("clips", {}))


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if not argv or argv[0] not in ("build", "validate"):
        sys.exit("usage: squads.py -- build|validate [<faction>/<id> ...]")
    units = [tuple(a.split("/", 1)) for a in argv[1:]] or all_squads()
    if argv[0] == "build":
        for faction, uid in units:
            build(faction, uid)
        return
    failed = 0
    print(f"squads: validating {len(units)} squad(s)")
    for faction, uid in units:
        errors = validate(faction, uid)
        print(f"  {'FAIL' if errors else 'ok':4} {faction}/{uid}")
        for e in errors:
            print(f"         - {e}")
        failed += bool(errors)
    if failed:
        sys.exit(f"squads: {failed} squad(s) failed")
    print("squads: all squads ok")


main()
